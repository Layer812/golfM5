// View from the sinking ball: the player is below the pond, looking up
// through the shrinking water surface to the sky. No camera spin/replay.
template<class D>
void drawUnderwater(D& d) {
    const float progress=clampf(game.waterClock/Game::WATER_VIEW_SECONDS,0.f,1.f);
    for(int y=0;y<screenH;y+=8) {
        float t=float(y)/float(screenH);
        d.fillRect(0,y,screenW,8,rgb(4+int(9*t),45-int(24*t),61-int(22*t)));
    }
    const int cx=S(233), cy=S(205+int(progress*24));
    const int rx=S(191.0f-progress*88.0f), ry=S(137.0f-progress*69.0f);
    d.fillEllipse(cx,cy,rx+S(14),ry+S(13),rgb(18,95,104));
    d.fillEllipse(cx,cy,rx+S(6),ry+S(6),rgb(39,143,159));
    d.fillEllipse(cx,cy,rx,ry,rgb(47+int(progress*13),149+int(progress*19),183+int(progress*14)));
    // Surface caustics and refracted daylight, seen through blue water.
    for(int i=1;i<=4;++i) {
        int rrx=(rx*i)/5, rry=(ry*i)/5;
        d.drawEllipse(cx,cy,rrx,rry,rgb(86+i*13,192+i*11,207+i*9));
    }
    d.fillCircle(cx-S(35),cy-S(28),S(13),rgb(191,226,219));
    for(int i=0;i<12;++i) {
        // Rising bubbles move upward while the observer sinks.
        float drift=fmodf(game.waterClock*(12.0f+float(i%5)*3.0f)+float(i*37),340.0f);
        int px=S(55+(i*73)%360), py=S(425.0f-drift);
        int radius=S(3+(i%3)*2);
        d.drawCircle(px,py,radius,rgb(91,184,200));
        if (i%3==0) d.fillCircle(px-S(1),py-S(1),S(2),rgb(166,223,228));
    }
    for (int i=0;i<7;++i) {
        int x=S(30+i*67);
        d.drawLine(x,screenH,x+S((i%2)?11:-13),S(360),rgb(14,70,65));
    }
}

template<class D>
void drawRavine(D &d, const Camera &cam) {
    const HoleLayout &c=game.course();
    if(c.terrain!=RAVINE) return;
    const float farZ=c.ravineEnd, nearZ=c.ravineStart;
    const float xl=-36.f, xr=36.f;
    Point a=cam.project(xl,farZ),b=cam.project(xr,farZ);
    Point l=cam.project(xl,nearZ),r=cam.project(xr,nearZ);
    triangle(d,a,b,l,rgb(39,46,39));triangle(d,b,l,r,rgb(31,38,38));
    Point lowA=cam.project(xl,farZ,-7.f),lowB=cam.project(xr,farZ,-7.f);
    triangle(d,a,b,lowA,rgb(89,81,61));triangle(d,b,lowA,lowB,rgb(64,59,52));
    if(l.ok&&r.ok) d.drawLine(l.x,l.y,r.x,r.y,rgb(189,168,126));
    if(a.ok&&b.ok) d.drawLine(a.x,a.y,b.x,b.y,rgb(188,158,109));
}

