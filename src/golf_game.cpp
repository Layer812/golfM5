void buzz(uint8_t strength, uint32_t durationMs) {
    if (!settingsVibration) return;
    M5.Power.setVibration(strength);
    vibrationEnabled = true;
    vibrationUntil = millis() + durationMs;
}
void sound(uint16_t hz, uint32_t ms) {
    if (!settingsSound) return;
    if (!speakerVolumeConfigured) {
        M5.Speaker.setVolume(100);
        speakerVolumeConfigured = true;
    }
    M5.Speaker.tone(hz, ms);
}
void afterTone(uint16_t hz, uint16_t ms, uint32_t delayMs) {
    pendingToneAt = millis() + delayMs;
    pendingToneFreq = hz;
    pendingToneDuration = ms;
}
// Speaker and panel setup are kept separate. Called after our own first
// display drawString and the game's initial screen render.
void primeGolfSpeaker() {
    if (!settingsSound) return;
    M5.Speaker.setVolume(112);
    speakerVolumeConfigured = true;
    // This silent playback wakes the audio path without replacing a real hit.
    (void)M5.Speaker.playRaw(kSpeakerWarmupSilence,
        sizeof(kSpeakerWarmupSilence)/sizeof(kSpeakerWarmupSilence[0]),
        kClubImpactSampleRate, false, 1, 0, true);
}
// M5Unified 0.2.21's int16_t playRaw returns bool on queue acceptance.
// Never drop the first driver impact silently if the speaker isn't ready.
void playClubImpact(const int16_t* data, size_t frameCount) {
    if (!settingsSound) return;
    if (!speakerVolumeConfigured) {
        M5.Speaker.setVolume(112);
        speakerVolumeConfigured = true;
    }
    queuedClubSound = nullptr;
    queuedClubFrames = 0;
    queuedClubRetries = 0;
    const bool ok=M5.Speaker.playRaw(data, frameCount, kClubImpactSampleRate,
                                     false, 1, 0, true);
    if (!ok) {
        queuedClubSound = data;
        queuedClubFrames = frameCount;
        queuedClubRetries = 4;
        nextClubRetryMs = millis()+25;
        Serial.println("BEG_R11 PCM queue rejected; retrying");
    }
}
void shotFX(bool putt, bool firstLongShot) {
    if (putt) {
        playClubImpact(kPutterImpactPCM,
                       sizeof(kPutterImpactPCM)/sizeof(kPutterImpactPCM[0]));
        buzz(90, 45);
    } else if (firstLongShot) {
        playClubImpact(kDriverImpactPCM,
                       sizeof(kDriverImpactPCM)/sizeof(kDriverImpactPCM[0]));
        buzz(210, 100);
    } else {
        playClubImpact(kSpoonImpactPCM,
                       sizeof(kSpoonImpactPCM)/sizeof(kSpoonImpactPCM[0]));
        buzz(210, 100);
    }
}
void landingFX() {
    sound(235, 80);
    buzz(125, 70);
}
void cupFX() {
    sound(1050, 55);
    afterTone(530, 165, 70);
    buzz(190, 130);
}
void updateFX() {
    uint32_t now=millis();
    if (queuedClubSound && (int32_t)(now-nextClubRetryMs)>=0) {
        if (!settingsSound) {
            queuedClubSound=nullptr;
        } else if (M5.Speaker.playRaw(queuedClubSound, queuedClubFrames,
                                     kClubImpactSampleRate,false,1,0,true)) {
            queuedClubSound=nullptr;
        } else if (queuedClubRetries>1) {
            --queuedClubRetries;
            nextClubRetryMs=now+35;
        } else {
            queuedClubSound=nullptr;
            // Fallback is audible even if the PCM queue couldn't initialize.
            M5.Speaker.tone(950,90);
            Serial.println("BEG_R11 PCM unavailable; tone fallback");
        }
    }
    if (vibrationUntil && (int32_t)(now - vibrationUntil) >= 0) {
        M5.Power.setVibration(0);
        vibrationEnabled = false;
        vibrationUntil=0;
    }
    if (pendingToneAt && (int32_t)(now - pendingToneAt) >= 0) {
        sound(pendingToneFreq,pendingToneDuration);
        pendingToneAt=0;
    }
}

struct Point { int x=0,y=0; bool ok=false; float depth=0; };
struct Camera {
    float x=0,z=0,h=.6f;
    float fX=0,fZ=1,rX=1,rZ=0;
    float focal=425, horizon=200;
    explicit Camera() {
        x=game.x; z=game.z;
        h=game.y+.62f;
        fX=game.aimX; fZ=game.aimZ;
        if (game.state == State::HOLED) h=.12f;
        rX=fZ; rZ=-fX;
        focal=screenW*.86f;
        // Slight view recoil in the air; no fast roll/pitch camera rotations.
        float airborne = game.state==State::AIRBORNE ? clampf(game.vy*.23f,-5,5) : 0;
        horizon=screenH*.405f+airborne;
    }
    Point project(float wx,float wz,float wy=0) const {
        float dx=wx-x, dz=wz-z;
        float d=dx*fX+dz*fZ;
        Point p;
        if (d < .85f) return p;
        p.depth=d;
        p.x=clipInt(clampf(screenW*.5f + (dx*rX+dz*rZ)*focal/d,
                             -110,screenW+110));
        p.y=clipInt(clampf(horizon + (h-wy)*focal/d,
                             -110,screenH+110));
        p.ok=true;
        return p;
    }
};

template<class D>
void triangle(D& d,Point a,Point b,Point c,uint16_t color) {
    if (a.ok && b.ok && c.ok)
        d.fillTriangle(a.x,a.y,b.x,b.y,c.x,c.y,color);
}
template<class D>
void groundDisc(D &d,const Camera &cam,float x,float z,float radius,uint16_t col) {
    Point mid=cam.project(x,z);
    if (!mid.ok) return;
    // Circle directions are cached; four discs used to require 160 trig calls
    // for every frame even though their world positions never change.
    for(int k=0;k<DISC_STEPS;++k) {
        int n=(k+1)%DISC_STEPS;
        Point pa=cam.project(x+radius*discCos[k],z+radius*discSin[k]);
        Point pb=cam.project(x+radius*discCos[n],z+radius*discSin[n]);
        triangle(d,mid,pa,pb,col);
    }
}
template<class D>
void groundEllipse(D &d, const Camera &cam, const HazardEllipse &h, float extra, uint16_t color) {
    Point mid=cam.project(h.x,h.z);
    if (!mid.ok) return;
    for (int k=0;k<DISC_STEPS;++k) {
        int n=(k+1)%DISC_STEPS;
        Point pa=cam.project(h.x+(h.rx+extra)*discCos[k],h.z+(h.rz+extra)*discSin[k]);
        Point pb=cam.project(h.x+(h.rx+extra)*discCos[n],h.z+(h.rz+extra)*discSin[n]);
        triangle(d,mid,pa,pb,color);
    }
}

template<class D>
void tree(D &d,const Camera &cam,float wx,float wz,uint16_t shade) {
    Point base=cam.project(wx,wz,0);
    Point tip=cam.project(wx,wz,7.5f);
    if (!base.ok || !tip.ok || base.y < -30 || tip.y>screenH+80) return;
    int r=(int)clampf((5.0f*cam.focal)/base.depth,2,78);
    if (r<3) return;
    int trunk=(int)clampf((1.0f*cam.focal)/base.depth,1,17);
    d.fillRect(base.x-trunk/2,tip.y+r/2,trunk,base.y-tip.y-r/2,rgb(83,64,35));
    d.fillTriangle(base.x-r,tip.y+r,base.x+r,tip.y+r,tip.x,tip.y-r/2,shade);
    d.fillTriangle(base.x-(int)(r*.8f),tip.y+(int)(r*.2f),
                   base.x+(int)(r*.8f),tip.y+(int)(r*.2f),tip.x,tip.y-r,
                   rgb(24,92,45));
}

