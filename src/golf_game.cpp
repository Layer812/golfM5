    d.fillTriangle(x2,y2,x2-(int)((dx*.75f-dy*.65f)*S(9)),
                   y2-(int)((dy*.75f+dx*.65f)*S(9)),
                   x2-(int)((dx*.75f+dy*.65f)*S(9)),
                   y2-(int)((dy*.75f-dx*.65f)*S(9)),col);
    char tmp[24];
    snprintf(tmp,sizeof(tmp),"%.1fm/s",game.windSpeed());
    textAt(d,tmp,225,159,cWhite);
