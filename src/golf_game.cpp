static void presentGame() {
    if (haveScene) {
        // The destination must finish reading PSRAM before we repaint it.
        M5.Display.waitDMA();
        render(scene);
        scene.pushSprite((screenW - SCENE_SIDE)/2, (screenH - SCENE_SIDE)/2);
        M5.Display.waitDMA();
    } else {
        // Safe fallback when PSRAM allocation fails. Keep the panel-owned
        // initialization unchanged and do not dereference a failed sprite.
        M5.Display.startWrite();
        render(M5.Display);
        M5.Display.endWrite();
    }
}


void resetForCurrentHole() {
    game.setHole(mode==GameMode::TOURNAMENT?currentHole:5);
    if(!settingsAutoAimToCup) game.setAutoAimToCup(false,true);
    refreshFairway();
    game.setWindSeed(++windRound*0x9E3779B9u+micros());
    if(vibrationEnabled) {M5.Power.setVibration(0);vibrationEnabled=false;}
    pendingToneAt=vibrationUntil=0;
    queuedClubSound=nullptr; queuedClubRetries=0;
    physicsCarry=0;
    lastPhysicsUs=micros();
    forceDraw=true;
    lastShotAtMs=lastLandingAtMs=lastWaterResetAtMs=0;
    lastShotPower=lastShotImpact=0.f;
}
void newGame() {
    currentHole=0;
    completedStrokes=completedPar=0;
    tournamentFinished=false;
    for(int &s:holeScores)s=0;
    for(float &d:driveDistances)d=0;
    bestDrive=0;
    driveAttempt=0;
    driveResult=driveFinished=false;
    driveTouchWasDown=false;
    resetForCurrentHole();
    // Do not reset gesture here: a replay touch remains captured until release.
}
void selectMode(GameMode selected) {
    mode=selected;
    newGame();
    menuOpen=false;
    gesture.reset();
    menuTouchWasDown=true;
    forceDraw=true;
}
void finishDrive(float distance) {
    if(driveResult || driveAttempt<1 || driveAttempt>DRIVE_ATTEMPTS)return;
    driveDistances[driveAttempt-1]=distance;
    if(distance>bestDrive)bestDrive=distance;
    driveResult=true;
    driveFinished=(driveAttempt==DRIVE_ATTEMPTS);
    game.vx=game.vy=game.vz=0;
    if(game.state!=State::HOLED) game.state=State::READY;
    forceDraw=true;
}
void nextDrive() {
    if(driveFinished) {newGame();return;}
    driveResult=false;
    resetForCurrentHole();
    gesture.reset();
}
void recordCup() {
    if(mode!=GameMode::TOURNAMENT || tournamentFinished)return;
    holeScores[currentHole]=game.shots;
    completedStrokes+=game.shots;
    completedPar+=game.holePar;
    if(currentHole==kHoleCount-1) tournamentFinished=true;
}
void advanceTournament() {
    if(tournamentFinished) {newGame();return;}
    if(currentHole < kHoleCount-1) ++currentHole;
    resetForCurrentHole();
    gesture.reset();
}
void fire() {
    const float chosenPower=game.currentPower;
    const float chosenImpact=game.hitSide;
    if(game.shoot()) {
        lastShotPower=chosenPower;
        lastShotImpact=chosenImpact;
        lastShotAtMs=millis();
        lastLandingAtMs=0;
        if(mode==GameMode::LONG_DRIVE) {
            ++driveAttempt;
            driveTeeX=game.prevShotX;driveTeeZ=game.prevShotZ;
            // Each of the three attempts is a driver shot.
            shotFX(false,true);
        } else {
            // One driver's first shot for every new hole, as intended.
            shotFX(game.lastWasPutt,game.shots==1);
        }
        forceDraw=true;
    }
}
void input() {
    auto td=M5.Touch.getDetail();
    const bool down=td.isPressed();
    // A completed hole accepts touch or EITHER physical button.
    // It is processed ahead of normal L=settings / R=shot.
    if(mode==GameMode::TOURNAMENT && game.state==State::HOLED) {
        if(M5.BtnA.wasPressed() || M5.BtnB.wasPressed()) {
            advanceTournament();return;
        }
        const TouchTarget a=gesture.update(down,td.x/unitScale,td.y/unitScale,
                                            true,game.hitSide);
        if(a==TouchTarget::REPLAY) advanceTournament();
        return;
    }
    // Menu remains available with the left button even on drive results.
    if(M5.BtnA.wasPressed()) {
        menuOpen=!menuOpen;
        menuTouchWasDown=down;
        gesture.reset();
        (void)M5.BtnB.wasPressed();
        physicsCarry=0;
        lastPhysicsUs=micros();
        forceDraw=true;
        return;
    }
    if(menuOpen) {
        (void)M5.BtnB.wasPressed();
        if(!down) {menuTouchWasDown=false;return;}
        if(menuTouchWasDown)return;
        menuTouchWasDown=true;
        const int row=menuRowAt(td.x/unitScale,td.y/unitScale);
        if(row==0) {selectMode(GameMode::TOURNAMENT);return;}
        if(row==1) {selectMode(GameMode::LONG_DRIVE);return;}
        if(row==2) {
            settingsAimStep=settingsAimStep==5?10:(settingsAimStep==10?1:5);
        } else if(row==3) {
            settingsAutoAimToCup=!settingsAutoAimToCup;
            game.setAutoAimToCup(settingsAutoAimToCup);
        } else if(row==4) {
            settingsSound=!settingsSound;
            if(!settingsSound){pendingToneAt=0;queuedClubSound=nullptr;}
            else primeGolfSpeaker();
        } else if(row==5) {
            settingsVibration=!settingsVibration;
            if(!settingsVibration&&vibrationEnabled) {
                M5.Power.setVibration(0);
                vibrationEnabled=false;vibrationUntil=0;
            }
        } else if(row==6) {
            menuOpen=false;
            gesture.reset();
        }
        forceDraw=true;
        return;
    }
    if(mode==GameMode::LONG_DRIVE && driveResult) {
        const bool right=M5.BtnB.wasPressed();
        const bool freshTouch=down&&!driveTouchWasDown;
        driveTouchWasDown=down;
        if(right||freshTouch)nextDrive();
        return;
    }
    // Right physical key alone initiates a shot.
    if(M5.BtnB.wasPressed() && game.state==State::READY) {fire();return;}
    const float ux=td.x/unitScale, uy=td.y/unitScale;
    TouchTarget a=gesture.update(down,ux,uy,false,game.hitSide);
    if(a==TouchTarget::AIM_LEFT&&game.state==State::READY) {
        game.steerAim(-1,settingsAimStep);forceDraw=true;
    } else if(a==TouchTarget::AIM_RIGHT&&game.state==State::READY) {
        game.steerAim(1,settingsAimStep);forceDraw=true;
    }
}
